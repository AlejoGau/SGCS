CREATE OR ALTER PROCEDURE [dbo].[SmartTrackIdByTelefono](@Telefono NVARCHAR(128))
as
select Id from [_datos].[dbo].[SmartTrack] where Telefono like '%'+RIGHT(@Telefono,8)